-- Run once in Supabase SQL Editor. Keeps existing products and IDs.
create table if not exists public.store_taxonomy (
  id bigint generated by default as identity primary key,
  kind text not null check(kind in ('department','category')),
  department text not null default '',
  name text not null,
  sort_order integer not null default 0,
  unique(kind,department,name)
);
insert into public.store_taxonomy(kind,department,name)
select distinct 'department','',department from public.products where department is not null and btrim(department)<>''
on conflict do nothing;
insert into public.store_taxonomy(kind,department,name)
select distinct 'category',department,category from public.products where department is not null and category is not null and btrim(category)<>''
on conflict do nothing;

create or replace function public.manage_store_taxonomy(p_action text,p_id bigint default null,p_name text default null,p_department text default null,p_sort integer default null)
returns void language plpgsql security invoker set search_path=public as $$
declare oldrow public.store_taxonomy%rowtype; clean_name text; clean_dept text;
begin
  clean_name:=btrim(coalesce(p_name,'')); clean_dept:=btrim(coalesce(p_department,''));
  if p_action='add_department' then
    if length(clean_name)<1 or length(clean_name)>50 then raise exception 'Department name must be 1–50 characters'; end if;
    insert into public.store_taxonomy(kind,department,name) values('department','',clean_name);
  elsif p_action='add_category' then
    if length(clean_name)<1 or length(clean_name)>100 then raise exception 'Category name must be 1–100 characters'; end if;
    if not exists(select 1 from public.store_taxonomy where kind='department' and name=clean_dept) then raise exception 'Choose an existing department'; end if;
    insert into public.store_taxonomy(kind,department,name) values('category',clean_dept,clean_name);
  else
    select * into oldrow from public.store_taxonomy where id=p_id for update;
    if not found then raise exception 'Entry not found'; end if;
    if p_action='rename' then
      if length(clean_name)<1 or length(clean_name)>100 then raise exception 'Name cannot be empty or too long'; end if;
      if oldrow.kind='department' then
        if length(clean_name)>50 then raise exception 'Department name too long'; end if;
        update public.store_taxonomy set name=clean_name where id=p_id;
        update public.store_taxonomy set department=clean_name where kind='category' and department=oldrow.name;
        update public.products set department=clean_name where department=oldrow.name;
        update public.category_discounts set department=clean_name where department=oldrow.name;
      else
        update public.store_taxonomy set name=clean_name where id=p_id;
        update public.products set category=clean_name where department=oldrow.department and category=oldrow.name;
        update public.category_discounts set category=clean_name where department=oldrow.department and category=oldrow.name;
      end if;
    elsif p_action='move' and oldrow.kind='category' then
      if not exists(select 1 from public.store_taxonomy where kind='department' and name=clean_dept) then raise exception 'Choose an existing department'; end if;
      update public.store_taxonomy set department=clean_dept where id=p_id;
      update public.products set department=clean_dept where department=oldrow.department and category=oldrow.name;
      update public.category_discounts set department=clean_dept where department=oldrow.department and category=oldrow.name;
    elsif p_action='delete' then
      if oldrow.kind='department' then
        if exists(select 1 from public.products where department=oldrow.name) or exists(select 1 from public.store_taxonomy where kind='category' and department=oldrow.name) or exists(select 1 from public.category_discounts where department=oldrow.name) then raise exception 'Move products and categories out of this department first'; end if;
      else
        if exists(select 1 from public.products where department=oldrow.department and category=oldrow.name) or exists(select 1 from public.category_discounts where department=oldrow.department and category=oldrow.name) then raise exception 'Move products and discounts out of this category first'; end if;
      end if;
      delete from public.store_taxonomy where id=p_id;
    elsif p_action='sort' then
      update public.store_taxonomy set sort_order=coalesce(p_sort,0) where id=p_id;
    else
      raise exception 'Unsupported action';
    end if;
  end if;
end $$;
-- Only the Netlify server (service_role) can invoke the management procedure.
revoke all on function public.manage_store_taxonomy(text,bigint,text,text,integer) from public,anon,authenticated;
grant execute on function public.manage_store_taxonomy(text,bigint,text,text,integer) to service_role;
